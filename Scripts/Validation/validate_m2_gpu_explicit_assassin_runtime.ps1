param([string]$ProjectRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..")))
$ErrorActionPreference = "Stop"
$runtimePath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_runtime.json"
$mapPath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_map_setup.json"
$screenshotPath = Join-Path $ProjectRoot "Docs\Validation\M2\Screenshots\M2_ExplicitAssassinCloth.png"
$comparisonCsvPath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_comparison.csv"
$comparisonJsonPath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_comparison.json"
$gpuTimingCsvPath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_gpu_timing.csv"
$reportPath = Join-Path $ProjectRoot "Docs\Validation\M2\gpu_explicit_assassin_validation.json"
if (-not (Test-Path -LiteralPath $runtimePath -PathType Leaf)) { throw "缺少显式拓扑运行报告：$runtimePath" }
if (-not (Test-Path -LiteralPath $mapPath -PathType Leaf)) { throw "缺少显式拓扑地图报告：$mapPath" }
$runtime = Get-Content -LiteralPath $runtimePath -Raw -Encoding UTF8 | ConvertFrom-Json
$map = Get-Content -LiteralPath $mapPath -Raw -Encoding UTF8 | ConvertFrom-Json
$comparison = Get-Content -LiteralPath $comparisonJsonPath -Raw -Encoding UTF8 | ConvertFrom-Json
$comparisonCsv = Import-Csv -LiteralPath $comparisonCsvPath -Encoding UTF8
$gpuTimingCsv = Import-Csv -LiteralPath $gpuTimingCsvPath -Encoding UTF8
$gpuValues = @($gpuTimingCsv | ForEach-Object { [double]$_.gpu_step_ms } | Sort-Object)
$gpuMean = if ($gpuValues.Count -gt 0) { ($gpuValues | Measure-Object -Average).Average } else { 0.0 }
$gpuMaximum = if ($gpuValues.Count -gt 0) { $gpuValues[-1] } else { 0.0 }
$gpuP95 = if ($gpuValues.Count -gt 0) { $gpuValues[[Math]::Max(0, [Math]::Ceiling(0.95 * $gpuValues.Count) - 1)] } else { 0.0 }
$gpuP99 = if ($gpuValues.Count -gt 0) { $gpuValues[[Math]::Max(0, [Math]::Ceiling(0.99 * $gpuValues.Count) - 1)] } else { 0.0 }
$gpuWarmupSteps = [int]$runtime.gpu_timing_warmup_steps
$gpuSteadyRows = @($gpuTimingCsv | Where-Object { [int]$_.step -gt $gpuWarmupSteps })
$gpuSteadyValues = @($gpuSteadyRows | ForEach-Object { [double]$_.gpu_step_ms } | Sort-Object)
$gpuSteadyMean = if ($gpuSteadyValues.Count -gt 0) { ($gpuSteadyValues | Measure-Object -Average).Average } else { 0.0 }
$gpuSteadyMaximum = if ($gpuSteadyValues.Count -gt 0) { $gpuSteadyValues[-1] } else { 0.0 }
$gpuSteadyP95 = if ($gpuSteadyValues.Count -gt 0) { $gpuSteadyValues[[Math]::Max(0, [Math]::Ceiling(0.95 * $gpuSteadyValues.Count) - 1)] } else { 0.0 }
$gpuSteadyP99 = if ($gpuSteadyValues.Count -gt 0) { $gpuSteadyValues[[Math]::Max(0, [Math]::Ceiling(0.99 * $gpuSteadyValues.Count) - 1)] } else { 0.0 }
$screenshot = if (Test-Path -LiteralPath $screenshotPath -PathType Leaf) { Get-Item -LiteralPath $screenshotPath } else { $null }
$checks = [ordered]@{
    runtime_passed = ($runtime.result -eq "passed")
    map_saved_without_errors = ($map.saved -eq $true -and @($map.errors).Count -eq 0)
    same_registered_component = ($runtime.same_component -eq $true -and $runtime.chaos_output_source -like "same registered Assassin component*")
    fixed_sixty_hz_contract = ($runtime.fixed_frame_contract_active -eq $true -and [Math]::Abs([double]$runtime.fixed_frame_delta_seconds - (1.0 / 60.0)) -lt 0.000001)
    chaos_timestep_smoothing_disabled = ($runtime.chaos_timestep_smoothing_disabled -eq $true)
    exact_assassin_topology = ([int]$runtime.particles -eq 2011 -and [int]$runtime.edges -eq 5714 -and [int]$runtime.fixed_vertices -eq 1307 -and [int]$runtime.dynamic_vertices -eq 704)
    three_hundred_fixed_steps = ([int]$runtime.steps_executed -eq 300 -and [int]$runtime.latest_readback_step -eq 300)
    twelve_explicit_modal_modes = ([int]$runtime.modal_mode_count -eq 12 -and [int]$runtime.modal_corrections -eq 300)
    rank_one_collision_every_step = ($runtime.rank_one_enabled -eq $true -and [int]$runtime.rank_one_collision_systems -eq 300)
    real_gpu_timestamp_supported = ($runtime.gpu_timing_supported -eq $true)
    gpu_timestamp_distribution_complete = ([int]$runtime.gpu_timing_samples -ge 30 -and [double]$runtime.mean_gpu_step_ms -gt 0.0 -and [double]$runtime.p95_gpu_step_ms -gt 0.0 -and [double]$runtime.p99_gpu_step_ms -ge [double]$runtime.p95_gpu_step_ms -and [double]$runtime.maximum_gpu_step_ms -ge [double]$runtime.p99_gpu_step_ms)
    gpu_scope_is_not_cpu_submission = ($runtime.gpu_timing_scope -like "RQT_AbsoluteTime interval*")
    gpu_raw_series_complete = (@($gpuTimingCsv).Count -eq [int]$runtime.gpu_timing_samples -and [int]$gpuTimingCsv[0].step -eq 1 -and [int]$gpuTimingCsv[-1].step -eq 300)
    gpu_raw_series_matches_summary = ([Math]::Abs($gpuMean - [double]$runtime.mean_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuP95 - [double]$runtime.p95_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuP99 - [double]$runtime.p99_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuMaximum - [double]$runtime.maximum_gpu_step_ms) -lt 0.000001)
    fixed_gpu_warmup_contract = ($gpuWarmupSteps -eq 16)
    gpu_steady_state_series_complete = ($gpuSteadyRows.Count -eq [int]$runtime.steady_state_gpu_timing_samples -and $gpuSteadyRows.Count -eq 284 -and [int]$gpuSteadyRows[0].step -eq 17 -and [int]$gpuSteadyRows[-1].step -eq 300)
    gpu_steady_state_matches_summary = ([Math]::Abs($gpuSteadyMean - [double]$runtime.mean_steady_state_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuSteadyP95 - [double]$runtime.p95_steady_state_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuSteadyP99 - [double]$runtime.p99_steady_state_gpu_step_ms) -lt 0.000001 -and [Math]::Abs($gpuSteadyMaximum - [double]$runtime.maximum_steady_state_gpu_step_ms) -lt 0.000001)
    every_animation_target_applied = ([int]$runtime.target_updates -eq 300 -and [int]$runtime.target_applications -eq 300 -and [int]$runtime.latest_target_version -eq 300)
    every_collision_snapshot_applied = ([int]$runtime.collision_updates -eq 300 -and [int]$runtime.collision_applications -eq 300 -and [int]$runtime.latest_collision_version -eq 300)
    explicit_complete_ccd_every_step = ([int]$runtime.complete_ccd_passes -eq 300)
    explicit_ndb_every_step = ([int]$runtime.ndb_state_updates -eq 300)
    ndb_capacity_matches_physics_asset = ([int]$runtime.collision_primitive_capacity -eq 17)
    exact_physics_asset_primitives = ([int]$runtime.collision_spheres -eq 1 -and [int]$runtime.collision_capsules -eq 16)
    live_animation_moves_boundary = ([double]$runtime.animation_target_motion_cm -gt 0.01)
    fixed_vertices_match_targets = ([double]$runtime.fixed_target_error_cm -le 0.001)
    dynamic_vertices_respond = ([double]$runtime.average_dynamic_displacement_cm -gt 0.01)
    structural_error_controlled = ([double]$runtime.maximum_edge_error_cm -lt 20.0)
    collision_penetration_removed = ([double]$runtime.maximum_collision_penetration_cm -lt 0.001)
    chaos_snapshots_captured = ([int]$runtime.chaos_snapshots -eq 300)
    paired_time_series_complete = ([int]$runtime.comparison_samples -eq 75 -and [int]$runtime.latest_compared_step -eq 300 -and @($comparison.samples).Count -eq 75 -and @($comparisonCsv).Count -eq 75)
    paired_time_series_bounds = ([int]$comparison.samples[0].step -eq 4 -and [int]$comparison.samples[-1].step -eq 300)
    paired_metrics_finite = (-not [double]::IsNaN([double]$runtime.latest_backend_mean_distance_cm) -and -not [double]::IsInfinity([double]$runtime.latest_backend_mean_distance_cm) -and -not [double]::IsNaN([double]$runtime.maximum_backend_distance_cm) -and -not [double]::IsInfinity([double]$runtime.maximum_backend_distance_cm))
    screenshot_present = ($null -ne $screenshot -and $screenshot.Length -gt 100000)
}
$report = [ordered]@{
    generated_at = (Get-Date).ToString("o")
    result = if ($checks.Values -contains $false) { "failed" } else { "passed" }
    checks = $checks
    evidence = [ordered]@{
        map = $map.map
        pose_source = $runtime.pose_source
        skinning_source = $runtime.skinning_source
        particles = [int]$runtime.particles
        edges = [int]$runtime.edges
        fixed_steps = [int]$runtime.steps_executed
        modal_mode_count = [int]$runtime.modal_mode_count
        modal_corrections = [int]$runtime.modal_corrections
        rank_one_collision_systems = [int]$runtime.rank_one_collision_systems
        gpu_timing_samples = [int]$runtime.gpu_timing_samples
        gpu_timing_samples_skipped = [int]$runtime.gpu_timing_samples_skipped
        mean_gpu_step_ms = [double]$runtime.mean_gpu_step_ms
        p95_gpu_step_ms = [double]$runtime.p95_gpu_step_ms
        p99_gpu_step_ms = [double]$runtime.p99_gpu_step_ms
        maximum_gpu_step_ms = [double]$runtime.maximum_gpu_step_ms
        gpu_timing_warmup_steps = $gpuWarmupSteps
        steady_state_gpu_timing_samples = [int]$runtime.steady_state_gpu_timing_samples
        mean_steady_state_gpu_step_ms = [double]$runtime.mean_steady_state_gpu_step_ms
        p95_steady_state_gpu_step_ms = [double]$runtime.p95_steady_state_gpu_step_ms
        p99_steady_state_gpu_step_ms = [double]$runtime.p99_steady_state_gpu_step_ms
        maximum_steady_state_gpu_step_ms = [double]$runtime.maximum_steady_state_gpu_step_ms
        gpu_timing_scope = $runtime.gpu_timing_scope
        gpu_timing_csv = $gpuTimingCsvPath
        target_updates = [int]$runtime.target_updates
        target_applications = [int]$runtime.target_applications
        collision_updates = [int]$runtime.collision_updates
        collision_applications = [int]$runtime.collision_applications
        collision_spheres = [int]$runtime.collision_spheres
        collision_capsules = [int]$runtime.collision_capsules
        complete_ccd_passes = [int]$runtime.complete_ccd_passes
        ndb_state_updates = [int]$runtime.ndb_state_updates
        latest_active_contact_pairs = [int]$runtime.latest_active_contact_pairs
        maximum_active_contact_pairs = [int]$runtime.maximum_active_contact_pairs
        maximum_ndb_activation = [int]$runtime.maximum_ndb_activation
        chaos_snapshots = [int]$runtime.chaos_snapshots
        comparison_samples = [int]$runtime.comparison_samples
        latest_compared_step = [int]$runtime.latest_compared_step
        latest_backend_mean_distance_cm = [double]$runtime.latest_backend_mean_distance_cm
        maximum_backend_distance_cm = [double]$runtime.maximum_backend_distance_cm
        latest_chaos_maximum_penetration_cm = [double]$runtime.latest_chaos_maximum_penetration_cm
        animation_target_motion_cm = [double]$runtime.animation_target_motion_cm
        fixed_target_error_cm = [double]$runtime.fixed_target_error_cm
        average_dynamic_displacement_cm = [double]$runtime.average_dynamic_displacement_cm
        maximum_edge_error_cm = [double]$runtime.maximum_edge_error_cm
        maximum_collision_penetration_cm = [double]$runtime.maximum_collision_penetration_cm
        screenshot = $screenshotPath
        comparison_csv = $comparisonCsvPath
        comparison_json = $comparisonJsonPath
        scope = "同一注册 Assassin SkeletalMeshComponent 在固定 60 Hz 应用帧合同下同时提供动画目标、Physics Asset 碰撞和 Chaos 输出；研究求解器读回按源步号配对，不要求两个不同算法数值相等"
    }
}
$report | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $reportPath -Encoding UTF8
if ($report.result -ne "passed") { throw "Assassin 显式拓扑运行验证失败：$reportPath" }
Write-Output "M2_GPU_EXPLICIT_ASSASSIN_VALIDATION_PASSED report=$reportPath"
